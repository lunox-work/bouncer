# Bouncer's marks, all in colour from one drawing: the movie bouncer, huge and heavyset in a black
# suit, bald, shades, arms crossed, a security earpiece with a coiled tube into his collar.
# assets/src/bouncer-flux.webp is FLUX.1 schnell (Apache 2.0) on AI Horde, 768px, 4 steps, cfg 1,
# k_euler, prompt:
#   soviet constructivist propaganda poster, red black and cream, flat colors, bold geometric
#   shapes, diagonal stripes behind him, flat cel-shaded black suit with warm charcoal highlights
#   and sharp shadow planes, no lettering, illustration of a huge heavyset nightclub bouncer built
#   like a crime boss enforcer, massive wide shoulders, barrel chest, thick bull neck, big powerful
#   heavyweight body, solid muscle with some heft, broad square jaw, a firm face with only slight
#   heaviness under the chin, bald head, small black sunglasses, stern frown, black suit and black
#   shirt, arms crossed over his chest, a security earpiece in his ear with a clear coiled tube
#   running down his neck into his collar, clearly visible earpiece, waist-up, camera at his chest
#   height looking up slightly, he faces the viewer straight on, symmetrical, shoulders square,
#   chin down, looking straight down at the viewer, no photo, no 3d render
# assets/src/bouncer-cut.webp is that drawing at 1024px with the poster cut away (rembg, u2net).
# Every mark is that cut-out with a thin paper ring round him so the black suit holds on a dark
# page as well as a light one: the big ones crop to his whole width, the small ones to his head
# (bald head, shades, earpiece), which is all that reads at 46px and under. Writes:
#   assets/mark.png           the README logo (shown at 180px)
#   assets/mark-small.png     the images' corner logo, his head (shown at 46px, 2x)
#   .claude-plugin/icon.png   the plugin icon: him on paper, his suit running off the bottom edge
#   bin/mark-art.mjs          his head, inlined in the verdict card (bin/card.mjs)
#   assets/badge.svg          its 14px logo, his head
# The hero's door scene is assets/src/scene.py. Needs: pip install pillow numpy
#   python assets/src/marks.py
import os, base64, io
from PIL import Image, ImageDraw, ImageFilter
import numpy as np

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, "..", "..")
CROP = (22, 0, 1008, 986)  # his whole width: round shoulders, the suit runs off the bottom
HEAD = (344, 0, 744, 400)  # his head and the top of his collar
PAPER = (242, 239, 232)

cut = Image.open(os.path.join(here, "bouncer-cut.webp")).convert("RGBA")
him, head = cut.crop(CROP), cut.crop(HEAD)
# just the head: his skin and whatever it encloses (shades, mouth), widened a little to keep the
# earbud; the collar and shoulders fall away, so the ring follows his jaw instead of boxing in the
# crop's edge. Then square it up round what is left.
h = np.asarray(head).copy()
skin = (h[..., 0].astype(int) - h[..., 2] > 35) & (h[..., 0] > 90) & (h[..., 3] > 128)
keep = Image.fromarray((skin * 255).astype(np.uint8)).filter(ImageFilter.MaxFilter(9)).copy()
for xy in ((0, 0), (keep.width - 1, 0), (0, keep.height - 1), (keep.width - 1, keep.height - 1)):
    if keep.getpixel(xy) == 0: ImageDraw.floodfill(keep, xy, 128)
h[np.asarray(keep) == 128, 3] = 0
head = Image.fromarray(h, "RGBA")
x0, y0, x1, y1 = head.getbbox(); side = max(x1 - x0, y1 - y0)
sq = Image.new("RGBA", (side, side), (0, 0, 0, 0)); sq.paste(head.crop((x0, y0, x1, y1)), ((side - (x1 - x0)) // 2, side - (y1 - y0)))
head = sq

def ringed(size, ring, src=him):
    """`src` at `size` px with a paper ring `ring` px wide (at that size), on transparent."""
    pad = ring + 1
    inner = src.resize((size - 2 * pad, size - 2 * pad), Image.LANCZOS)
    out = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    out.paste(inner, (pad, pad), inner)
    a = out.split()[3].filter(ImageFilter.MaxFilter(2 * ring + 1)).filter(ImageFilter.GaussianBlur(0.6))
    ring_img = Image.new("RGBA", (size, size), PAPER + (255,)); ring_img.putalpha(a)
    ring_img.alpha_composite(out)
    return ring_img

ringed(480, 5).save(os.path.join(root, "assets", "mark.png"), optimize=True)
ringed(96, 2, head).save(os.path.join(root, "assets", "mark-small.png"), optimize=True)

icon = Image.new("RGBA", (1024, 1024), PAPER + (255,))
big = him.resize((960, 960), Image.LANCZOS)
icon.alpha_composite(big, (32, 104))
icon.convert("RGB").save(os.path.join(root, ".claude-plugin", "icon.png"), optimize=True)

buf = io.BytesIO(); ringed(112, 2, head).save(buf, "PNG", optimize=True)  # shown at 56px, so 2x
with open(os.path.join(root, "bin", "mark-art.mjs"), "w") as f:
    f.write("// Generated by assets/src/marks.py from assets/src/bouncer-cut.webp: do not edit by hand.\n")
    f.write("// Bouncer in colour, 112px square PNG with a paper ring, for the verdict card.\n")
    f.write(f'export const MARK_PNG = "data:image/png;base64,{base64.b64encode(buf.getvalue()).decode()}";\n')

# the README badge (assets/badge.svg, shields.io's flat-square shape): swap its 14px logo for his head
badge = os.path.join(root, "assets", "badge.svg")
buf = io.BytesIO(); ringed(28, 1, head).save(buf, "PNG", optimize=True)
import re
svg = open(badge).read()
svg = re.sub(r'(<image x="5" y="3" width="14" height="14" href=")[^"]+"', lambda m: m.group(1) + "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode() + '"', svg, count=1)
open(badge, "w").write(svg)
